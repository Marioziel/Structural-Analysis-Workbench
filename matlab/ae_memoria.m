             "\varphi=\frac{64MDn}{Ed^4}="+num(r.giro)+"\ \mathrm{rad}"]);
    else
        espacial=d.modo=="espacial";
        marco(r,espacial);
    end
case "tensor"
    pagina('Estado de tensión y ley de Hooke','El tensor es simétrico. Las componentes de deformación fuera de la diagonal son tensoriales: gamma_xy=2 epsilon_xy. La temperatura añade alpha DeltaT a las tres componentes normales.', ...
