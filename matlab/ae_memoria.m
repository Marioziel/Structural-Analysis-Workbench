         "\mathbf t=\boldsymbol\sigma\mathbf n,\quad\sigma_n=\mathbf n^T\mathbf t="+num(e.sigmaNormal/1e6)+"\ \mathrm{MPa}", ...
         "\tau_n=\|\mathbf t-\sigma_n\mathbf n\|="+num(e.tauCara/1e6)+"\ \mathrm{MPa},\quad n_{VM}="+num(e.nVM)]);
case "resistencia_combinada"
    if d.modo=="estructura",marco(r.marco,true);end
    pagina('Sección circular de comprobación','Los momentos son vectores físicos según la regla de la mano derecha. En modo sección aislada se aplica la conversión de My de la convención de sección a la vectorial. Las dimensiones son las calculadas, incluido el dimensionamiento si se seleccionó.', ...
