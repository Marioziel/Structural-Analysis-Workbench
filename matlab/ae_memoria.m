        "\boldsymbol\varepsilon=\frac{1+\nu}{E}\boldsymbol\sigma-\frac{\nu}{E}\mathrm{tr}(\boldsymbol\sigma)\mathbf I+\alpha\Delta T\mathbf I", ...
        "\det(\boldsymbol\sigma-\sigma_i\mathbf I)=0", ...
        "(\sigma_1,\sigma_2,\sigma_3)=("+num(r.principales(1)/1e6)+","+num(r.principales(2)/1e6)+","+num(r.principales(3)/1e6)+")\ \mathrm{MPa}"]);
    pagina('Criterios y cara de consulta','La normal de consulta se normaliza antes de obtener el vector de tracción. Los factores corresponden al límite elástico introducido.', ...
        ["\sigma_{VM}=\sqrt{\frac{(\sigma_1-\sigma_2)^2+(\sigma_2-\sigma_3)^2+(\sigma_3-\sigma_1)^2}{2}}="+num(r.VM/1e6)+"\ \mathrm{MPa}", ...
