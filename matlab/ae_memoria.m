case "seccion"
    pagina('Propiedades geométricas de la sección','Las inercias se refieren al centroide. Las paredes delgadas omiten contribuciones del orden del espesor al cubo.', ...
        ["F=\int_D dA="+num(r.F)+"\ \mathrm{m^2}", ...
        "(y_c,z_c)=\frac{1}{F}\int_D(y,z)dA=("+num(r.centro(1))+","+num(r.centro(2))+")\ \mathrm{m}", ...
        "I_y=\int_D(z-z_c)^2dA="+num(r.Iy)+"\ \mathrm{m^4}", ...
        "I_z=\int_D(y-y_c)^2dA="+num(r.Iz)+"\ \mathrm{m^4}", ...
        "I_{yz}=\int_D(y-y_c)(z-z_c)dA="+num(r.Iyz)+"\ \mathrm{m^4}"]);
