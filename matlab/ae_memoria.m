        ["\mathbf J=\begin{bmatrix}I_y&-I_{yz}\\-I_{yz}&I_z\end{bmatrix},\quad\mathbf J\mathbf v_k=I_k\mathbf v_k", ...
         "(I_1,I_2)=("+num(r.principales(1))+","+num(r.principales(2))+")\ \mathrm{m^4}", ...
         "i_k=\sqrt{I_k/F},\quad(i_1,i_2)=("+num(r.radios(1))+","+num(r.radios(2))+")\ \mathrm{m}"]);
case "torsion"
    pagina('Torsión de Saint-Venant','J es la constante de torsión y W el módulo resistente torsional. La correspondencia con una barra axial permite resolver compatibilidad de giros y equilibrio de pares.', ...
        ["\frac{dM_t}{ds}+m_t=0,\qquad\frac{d\varphi}{ds}=\frac{M_t}{GJ}", ...
         "\tau_{max}=\frac{|M_t|}{W}","\varphi_b-\varphi_a=\int_a^b\frac{M_t}{GJ}\,ds"]);
    for j=indices(numel(r.tramos))
        t=r.tramos(j);k=r.modelo.indiceOriginal(j);
        pagina(sprintf('Tramo %d: momento, tensión y giro',j),'s se mide desde el inicio del tramo. La curva de cortante conserva el signo del momento; su valor absoluto es la tensión máxima.', ...
          ["0\leq s\leq"+num(t.L)+"\ \mathrm{m}", ...
          "M_t(s)="+pol(t.N)+"\quad[\mathrm{N\,m}]", ...
          "\tau(s)=\frac{M_t(s)}{"+num(valor(e.W,k))+"}="+pol(t.N/valor(e.W,k)/1e6)+"\quad[\mathrm{MPa}]", ...
          "\varphi(s)="+pol(t.delta)+"\quad[\mathrm{rad}]"]);
    end
case "viga"
    pagina('Flexión de Euler-Bernoulli','La sección permanece plana. En la convención del modelo plano, M=EI v'''' y V=M''. Las cargas actúan en el plano de la viga.', ...
