    if d.modo=="estructura"
        crit=rm_circular_combinada(e.N,e.Qy,e.Qz,e.T,e.MyVector,e.Mz,e.Dcrit,e.dicrit,d.nu,d.limiteTraccion/d.limiteCompresion);
        peor=r.maximos(r.barraCritica,d.teoria);factor=r.factor;
    else
        crit=r;vals=r.envolvente;if ~d.considerarCortante,vals=r.nominal;end
        peor=vals(d.teoria);factor=d.limiteTraccion/max(peor,realmin);
    end
    pagina('Criterio resistente seleccionado', ...
        sprintf('Teoría %d. El cortante transversal usa una envolvente basada en Jourawski. No equivale a un campo exacto de elasticidad tridimensional ni incluye concentración en uniones.',d.teoria), ...
        ["\tau_Q^{cota}="+num(crit.tauQ/1e6)+"\ \mathrm{MPa},\quad\tau^{cota}=\tau_T+\tau_Q^{cota}", ...
         "\sigma_{eq}="+criterio(d.teoria), ...
         "\sigma_{eq,max}="+num(peor/1e6)+"\ \mathrm{MPa}", ...
         "n=\frac{[\sigma]_t}{\sigma_{eq,max}}="+num(factor)+",\qquad n_{requerido}="+num(d.nRequerido)]);
case "lamina"
    pagina('Equilibrio de membrana axisimétrica','Nm y Nt son fuerzas por unidad de longitud. Las curvaturas km y kt determinan el equilibrio normal de Laplace. La fuerza inicial incluye la presión sobre la tapa y la fuerza axial extra.', ...
        ["F_z(r)=F_{z,0}+\int_{r_0}^{r}2\pi p(\rho)\rho\,d\rho", ...
         "N_m=\frac{F_z}{2\pi r\cos\beta},\qquad k_mN_m+k_\theta N_\theta=p", ...
         "\sigma_m=\frac{N_m}{t},\quad\sigma_\theta=\frac{N_\theta}{t}", ...
         "\sigma_{VM}=\sqrt{\sigma_m^2+\sigma_\theta^2-\sigma_m\sigma_\theta}", ...
         "n=\frac{\sigma_y}{\max\sigma_{VM}}="+num(r.factor)]);
    for j=indices(numel(e.z))
        if isempty(op.elementos)&&~ismember(j,[1 numel(e.z)]),continue;end
        pagina(sprintf('Estación meridional %d',j),'Valores en la estación indicada. Estas ecuaciones son de membrana; no describen flexión local en bordes o uniones.', ...
            ["z="+num(e.z(j))+"\ \mathrm{m},\quad r="+num(e.r(j))+"\ \mathrm{m},\quad p="+num(e.p(j)/1e6)+"\ \mathrm{MPa}", ...
             "N_m="+num(e.Nm(j))+"\ \mathrm{N/m},\quad N_\theta="+num(e.Nt(j))+"\ \mathrm{N/m}", ...
             "\sigma_m="+num(r.sigmaM(j)/1e6)+"\ \mathrm{MPa},\quad\sigma_\theta="+num(r.sigmaT(j)/1e6)+"\ \mathrm{MPa}"]);
    end
case "estabilidad"
    pagina('Estabilidad de la columna en dos planos principales','La carga crítica se obtiene del problema de valores propios. La solución de segundo orden es válida por debajo de la carga crítica y dentro del régimen elástico.', ...
        ["\det(\mathbf K-P_{cr}\mathbf G)=0", ...
         "P_E=\frac{\pi^2EI}{(\mu L)^2},\quad P_{cr}=\min(P_{cr,Y},P_{cr,Z})", ...
         "P_{cr}="+num(r.Pcritica)+"\ \mathrm{N},\quad\sigma_{cr}=P_{cr}/F="+num(e.sigmaCritica/1e6)+"\ \mathrm{MPa}", ...
         "(\mathbf K-P\mathbf G)\mathbf u=\mathbf f,\quad P="+num(d.P)+"\ \mathrm{N}", ...
         "P_{cr}/P="+num(r.margen)]);
    pagina('Comprobación de aplicabilidad elástica','Si sigma_cr supera el límite proporcional, el valor de Euler no es una capacidad resistente válida del material. Refina elementos y compara la carga crítica y la flecha.', ...
        ["\sigma_{cr}\leq\sigma_{proporcional}="+num(d.limiteProporcional/1e6)+"\ \mathrm{MPa}", ...
         "\mathrm{Euler\ aplicable}="+num(double(e.EulerAplicable)), ...
         "\max|u_Y|="+num(max(abs(r.u(:,1))))+"\ \mathrm{m},\quad\max|u_Z|="+num(max(abs(r.u(:,2))))+"\ \mathrm{m}"]);
case "dinamica"
    if d.modo=="rotacion"
        pagina('Barra radial en rotación','La fuerza de inercia por unidad de longitud aumenta linealmente con el radio. La velocidad angular es constante.', ...
            ["q(x)=\rho F\omega^2(r_0+x)", ...
             "\omega="+num(d.omega)+"\ \mathrm{rad/s},\quad\rho="+num(d.densidad)+"\ \mathrm{kg/m^3}"]);
        axial(r);
    else
        pagina('Impacto: balance energético','El impacto se reduce a una rigidez estática equivalente. No se incluye amortiguamiento ni la inercia distribuida de la estructura. Se presenta el máximo, no una historia temporal.', ...
            ["v_i=\sqrt{v_0^2+2gh}="+num(e.velocidadImpacto)+"\ \mathrm{m/s}", ...
             "\frac{k\delta_{max}^2}{2}=\frac{mv_i^2}{2}+mg\delta_{max}", ...
             "\delta_{max}=\frac{mg+\sqrt{(mg)^2+kmv_i^2}}{k}="+num(r.deltaMax)+"\ \mathrm{m}", ...
             "P_{max}=k\delta_{max}="+num(r.fuerzaMax)+"\ \mathrm{N},\quad k="+num(r.rigidez)+"\ \mathrm{N/m}", ...
             "k_d=\frac{\delta_{max}}{mg/k}="+num(r.factorDinamico)]);
        if isfield(e,'marcoImpacto'),marco(e.marcoImpacto,true);end
    end
case "plasticidad"
    if d.modo=="axial"
        eq="\sigma_i=\max(-\sigma_y,\min(E\delta/L_i,\sigma_y)),\quad P=\sum_i\sigma_iF_i";
        lim="P_{lim}=\sigma_y\sum_iF_i";unidad="\mathrm{N}";
    elseif d.modo=="flexion"
        eq="\sigma(y)=\max(-\sigma_y,\min(-E\kappa(y-y_0),\sigma_y)),\quad\int_D\sigma\,dA=0";
        lim="M_{lim}=\sigma_y\int_D|y-y_p|dA";unidad="\mathrm{N\,m}";
    else
        eq="\tau(r)=\min(G\varphi' r,\tau_y),\quad T=2\pi\int_{r_i}^{R}\tau(r)r^2dr";
        lim="T_{lim}=\frac{2\pi\tau_y}{3}(R^3-r_i^3)";unidad="\mathrm{N\,m}";
    end
    pagina('Respuesta ideal elastoplástica monótona','El límite se obtiene del equilibrio con la tensión plástica. No se simula descarga, endurecimiento ni comportamiento cíclico.', ...
        [eq,lim+"="+num(r.limite)+"\ "+unidad, ...
         "\mathrm{Respuesta\ final}="+num(r.respuesta(end))+"\ "+unidad]);
case "fatiga"
    pagina('Amplitud, media y combinación de seguridad','Cada fila de ciclos corresponde a un punto de evaluación con extremos conocidos de sigma y tau. Los coeficientes y límites son datos del material y del detalle analizado.', ...
        ["\sigma_a=\frac{\sigma_{max}-\sigma_{min}}{2},\quad\sigma_m=\frac{\sigma_{max}+\sigma_{min}}{2}", ...
         "n_{\sigma,f}=\frac{\sigma_{-1}}{K_\sigma\sigma_a+\psi_\sigma\sigma_m},\quad n_{\tau,f}=\frac{\tau_{-1}}{K_\tau\tau_a+\psi_\tau\tau_m}", ...
         "n_\sigma=\min(n_{\sigma,f},n_{\sigma,est}),\quad n_\tau=\min(n_{\tau,f},n_{\tau,est})", ...
         "n=\left(\frac{1}{n_\sigma^2}+\frac{1}{n_\tau^2}\right)^{-1/2}"]);
    pagina('Control de máximos estáticos en un ciclo', ...
        'Los límites de tracción, compresión y cortante se introducen por separado. La amplitud se multiplica por el coeficiente de concentración utilizado en este modelo.', ...
        ["n_{\sigma,est}=\min\left(\frac{[\sigma]_t}{K_\sigma\sigma_a+\sigma_m},\frac{[\sigma]_c}{K_\sigma\sigma_a-\sigma_m}\right)", ...
         "n_{\tau,est}=\frac{[\tau]}{K_\tau\tau_a+|\tau_m|}", ...
         "\tau_a=\frac{\tau_{max}-\tau_{min}}{2},\quad\tau_m=\frac{\tau_{max}+\tau_{min}}{2}"]);
    for j=indices(height(r))
        pagina(sprintf('Punto %d: comprobación de fatiga',j),'Se comprueban conjuntamente fatiga y máximos estáticos. El margen se refiere al factor requerido.', ...
            ["\sigma_a="+num(e.sa(j)/1e6)+"\ \mathrm{MPa},\quad\sigma_m="+num(e.sm(j)/1e6)+"\ \mathrm{MPa}", ...
             "\tau_a="+num(e.ta(j)/1e6)+"\ \mathrm{MPa},\quad\tau_m="+num(e.tm(j)/1e6)+"\ \mathrm{MPa}", ...
             "n_\sigma="+num(e.nNormal(j))+",\quad n_\tau="+num(e.nCortante(j)), ...
             "n="+num(e.nCombinado(j))+",\quad n_{requerido}="+num(d.nRequerido)]);
    end
case "barra_curva"
    pagina('Barra de gran curvatura','El radio neutro difiere del radio centroidal. La tensión depende de 1/r y no de una ley lineal respecto al radio.', ...
        ["F=\int b(r)dr="+num(r.F)+"\ \mathrm{m^2}", ...
         "R=\frac{\int rb(r)dr}{F}="+num(r.R)+"\ \mathrm{m}", ...
         "r_n=\frac{F}{\int b(r)/r\,dr}="+num(r.rn)+"\ \mathrm{m},\quad e=R-r_n="+num(r.e)+"\ \mathrm{m}", ...
         "\sigma(r)=\frac{N}{F}+\frac{M}{Fe}\left(1-\frac{r_n}{r}\right)"]);
    if d.modo=="arco"
        eqArco="\delta=\int\left[\frac{Mm}{EFeR}+\frac{Nn}{EF}+\frac{Mn+Nm}{EFR}\right]ds";
        if d.incluirCortante,eqArco=eqArco+"+\int\frac{k_QQq}{GF}\,ds";end
        pagina('Desplazamiento del arco por trabajo virtual','La fuerza y la dirección de consulta pertenecen al plano local del arco. El término de cortante se añade únicamente si incluirCortante es verdadero.', ...
            [eqArco, ...
             "\delta="+num(r.delta)+"\ \mathrm{m},\quad U="+num(r.energia)+"\ \mathrm{J}"]);
    else
        pagina('Sección curva: sustitución de esfuerzos','N y M se introducen en los datos de sección.', ...
            ["N="+num(d.Nseccion)+"\ \mathrm{N},\quad M="+num(d.Mseccion)+"\ \mathrm{N\,m}", ...
             "\sigma_{min}="+num(min(r.sigma)/1e6)+"\ \mathrm{MPa},\quad\sigma_{max}="+num(max(r.sigma)/1e6)+"\ \mathrm{MPa}"]);
    end
case "compatibilidad"
    if d.modo=="compatibilidad"
        pagina('Compatibilidad de la plataforma rígida','Para una barra rígida 2D se usa B=[1 x]; para la plataforma 3D se usa B=[1 x y]. Los tirantes del modelo son bilaterales: pueden desarrollar tracción y compresión.', ...
