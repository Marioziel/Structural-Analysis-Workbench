function t=mat(a,n)
a=a(1:min(size(a,1),n),1:min(size(a,2),n));filas=strings(size(a,1),1);
for i=1:size(a,1)
    valores=strings(1,size(a,2));for j=1:size(a,2),valores(j)=num(a(i,j));end
    filas(i)=strjoin(valores,'&');
end
t="\begin{bmatrix}"+strjoin(filas,'\\\\')+"\end{bmatrix}";
end
function t=criterio(k)
switch k
case 1,t="\max(|\sigma_1|,|\sigma_3|)";
case 2,t="\max(|\sigma_1-\nu(\sigma_2+\sigma_3)|,|\sigma_3-\nu(\sigma_1+\sigma_2)|)";
case 3,t="\sqrt{\sigma^2+4\tau^2}";
case 4,t="\sqrt{\sigma^2+3\tau^2}";
case 5,t="\frac{(1-k)\sigma+(1+k)\sqrt{\sigma^2+4\tau^2}}{2},\quad k=\frac{[\sigma]_t}{[\sigma]_c}";
end
end
