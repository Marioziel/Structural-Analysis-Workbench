        "\sigma_{min}="+num(r.sigmaMin/1e6)+"\ \mathrm{MPa},\quad\sigma_{max}="+num(r.sigmaMax/1e6)+"\ \mathrm{MPa}"]);
case "sistema_barras"
    if d.modo=="resorte"
        pagina('Resorte helicoidal de pequeño paso','La carga axial produce torsión del alambre; el par aplicado produce la respuesta angular indicada. D es el diámetro medio y d el diámetro del alambre.', ...
