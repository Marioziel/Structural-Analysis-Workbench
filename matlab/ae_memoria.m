paginas=struct('titulo',{},'explicacion',{},'ecuaciones',{});
switch s.analisis
case "axial"
    axial(r);
case "cercha"
    pagina('Compatibilidad y equilibrio de la cercha', ...
        'Las uniones son articuladas. Cada barra transmite únicamente esfuerzo axial. La deformación libre se resta de la deformación geométrica.', ...
