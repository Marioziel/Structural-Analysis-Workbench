                 "N=\frac{EF}{L}(\delta-\delta^0)="+num(r.N(j))+"\ \mathrm{N}", ...
                 "\sigma=N/F="+num(r.sigma(j)/1e6)+"\ \mathrm{MPa}"]);
        end
    else
        pagina('Transferencia de carga mediante adhesivo','La base es rígida y la ley de cortante del adhesivo es lineal. La solución verifica la transferencia de la fuerza a lo largo de la unión.', ...
            ["\beta=\sqrt{\frac{k_a}{Et}}="+num(r.beta)+"\ \mathrm{m^{-1}}", ...
             "N(x)=P\frac{\sinh(\beta x)}{\sinh(\beta L)}", ...
             "\tau(x)=\frac{P\beta}{b}\frac{\cosh(\beta x)}{\sinh(\beta L)},\quad u=\frac{\tau}{k_a}", ...
             "\max|\tau|="+num(max(abs(r.tau))/1e6)+"\ \mathrm{MPa}", ...
             "\int_0^L\tau b\,dx-P="+num(r.residuoTransferencia)+"\ \mathrm{N}"]);
