memoria=struct('analisis',s.analisis,'fecha',s.fecha,'entrada',d,'paginas',paginas, ...
    'nota',"Expresiones y cifras generadas desde los datos y resultados de esta ejecucion; unidades SI salvo indicacion.");

    function pagina(titulo,explicacion,eq)
        if isfield(s,'caso'),titulo=string(s.caso)+" | "+string(titulo);end
        eq=string(eq);
        paginas(end+1)=struct('titulo',string(titulo),'explicacion',string(explicacion),'ecuaciones',eq);
        ae_pagina(titulo,explicacion,eq);
    end
    function ix=indices(n)
        ix=op.elementos;if isempty(ix),ix=1:n;end
        assert(isnumeric(ix)&&isvector(ix)&&all(isfinite(ix))&&all(ix==fix(ix)&ix>=1&ix<=n), ...
            'AE:Memoria','elementos debe contener indices enteros entre 1 y %d.',n);
        ix=unique(ix(:).','stable');
    end
    function axial(a)
        m=a.modelo;Q=sum(diff(m.x).*mean(m.q,2));
        pagina('Equilibrio axial y condiciones de compatibilidad','Las cargas positivas y los desplazamientos positivos apuntan hacia x creciente. Las reacciones se obtienen simultáneamente con los desplazamientos cuando hay varios apoyos. Los contactos activos también aportan reacción.', ...
            ["\sum R+\sum P+\int q\,dx=0", ...
             "("+num(sum(a.R))+")+("+num(sum(m.P))+")+("+num(Q)+")="+num(sum(a.R)+sum(m.P)+Q)+"\quad[\mathrm N]", ...
             "N'+q=0,\quad\sigma=\frac{N}{F},\quad\varepsilon=\frac{N}{EF}+\alpha\Delta T,\quad\delta'=\varepsilon"]);
        for k=indices(numel(a.tramos))
            b=a.tramos(k);
            pagina(sprintf('Tramo %d: x = %.5g a %.5g m',k,b.x0,b.x0+b.L), ...
                sprintf('Coordenada local s=x−%.5g m, 0≤s≤%.5g m. F=%.6g m²; E=%.6g Pa. La constante del desplazamiento impone continuidad con el nodo inicial.',b.x0,b.L,m.F(k),m.E(k)), ...
                ["N(s)=N(0)-\int_0^s q(\xi)d\xi="+pol(b.N)+"\quad[\mathrm N]", ...
                 "\sigma(s)=\frac{N(s)}{"+num(m.F(k))+"}="+pol(b.sigma/1e6)+"\quad[\mathrm{MPa}]", ...
                 "\varepsilon(s)=\frac{N(s)}{EF}+\alpha\Delta T(s)="+pol(b.epsilon), ...
                 "\delta(s)=\delta(0)+\int_0^s\varepsilon(\xi)d\xi="+pol(b.delta)+"\quad[\mathrm m]", ...
                 "\delta("+num(b.L)+")="+num(polyval(b.delta,b.L))+"\ \mathrm m"]);
        end
    end
    function matriz(a)
        u=reshape(a.u.',[],1);rr=reshape(a.R.',[],1);res=norm(a.K*u-a.f-rr,inf);
        fijo=[];prescrito=[];
        if isfield(a,'datos')&&isfield(a.datos,'apoyos')
            ap=a.datos.apoyos;nd=size(a.u,2);
            for ii=1:size(ap,1)
                jj=find(~isnan(ap(ii,2:end)));fijo=[fijo (ap(ii,1)-1)*nd+jj];prescrito=[prescrito ap(ii,jj+1)];
            end
        end
        libres=setdiff(1:numel(u),fijo);nf=numel(libres);
        pagina('Sistema global y condiciones de contorno', ...
            sprintf('Orden por nodo: traslaciones y después giros, cuando existen. El modelo tiene %d grados de libertad; %d restricciones prescritas y %d grados restantes. f incluye cargas equivalentes y deformaciones libres. Las rótulas pueden requerir referencias de giro adicionales.',numel(u),numel(fijo),nf), ...
            ["\begin{bmatrix}\mathbf K_{ff}&\mathbf K_{fc}\\\mathbf K_{cf}&\mathbf K_{cc}\end{bmatrix}\begin{bmatrix}\mathbf u_f\\\overline{\mathbf u}_c\end{bmatrix}=\begin{bmatrix}\mathbf f_f\\\mathbf f_c+\mathbf R_c\end{bmatrix}", ...
             "\mathbf K_{ff}\mathbf u_f=\mathbf f_f-\mathbf K_{fc}\overline{\mathbf u}_c", ...
             "\mathbf R=\mathbf K\mathbf u-\mathbf f", ...
             "\|\mathbf K\mathbf u-\mathbf f-\mathbf R\|_\infty="+num(res)]);
        if nf>0
            idx=libres(1:min([nf op.maxFilasMatriz 4]));
            txt=sprintf('Se muestran las filas y columnas globales %s. Es una vista parcial cuando no contiene todos los grados libres; el cálculo usa la matriz completa. K combina unidades según traslaciones y giros; f combina N y N m.',mat2str(idx));
            pagina('Valores del sistema: extracto de presentación',txt, ...
                ["\mathbf K_{vista}="+mat(full(a.K(idx,idx)),4), ...
                 "\mathbf u_{vista}="+mat(u(idx),4), ...
                 "\mathbf f_{vista}="+mat(a.f(idx),4)]);
        end
    end
    function marco(a,espacial)
        if espacial
            pagina('Modelo espacial de barras','Cada nodo posee tres traslaciones y tres giros. Las inercias deben corresponder a los ejes principales locales. Se omite la deformación por cortante y el alabeo restringido.', ...
                ["N=EF(u'-\varepsilon^0),\quad T=GJ(\varphi'-\varphi'_0)", ...
                 "M_z=EI_z(v''-\kappa_z^0),\quad M_y=-EI_y(w''+\kappa_y^0)", ...
                 "Q_y=-M_z',\quad Q_z=M_y'", ...
                 "\mathbf K_e^{global}=\mathbf T_e^T\mathbf K_e^{local}\mathbf T_e"]);
        else
            pagina('Modelo plano de barras','Cada nodo posee dos traslaciones y un giro. La convención de los campos planos es V=M''.', ...
                ["N=EF(u'-\varepsilon^0),\quad M=EI(v''-\kappa^0),\quad V=M'", ...
                 "\mathbf K_e^{global}=\mathbf T_e^T\mathbf K_e^{local}\mathbf T_e"]);
        end
        matriz(a);campos(a,espacial);
        if isfield(a,'deltaMohr')
            eq="\delta=\sum_e\int\left(\frac{Nn}{EF}+\frac{Mm}{EI}\right)ds+\delta_0-\mathbf R_v^T\overline{\mathbf u}";
            if espacial,eq="\delta=\sum_e\int\left(\frac{Nn}{EF}+\frac{Tt}{GJ}+\frac{M_y m_y}{EI_y}+\frac{M_z m_z}{EI_z}\right)ds+\delta_0-\mathbf R_v^T\overline{\mathbf u}";end
            pagina('Trabajo virtual: comprobación independiente del desplazamiento','delta_0 reúne las contribuciones de deformaciones libres. Las reacciones virtuales permiten incluir los movimientos prescritos de los apoyos. La respuesta es m para una fuerza unitaria o rad para un par unitario.', ...
                [eq,"\delta_{nodal}="+num(a.deltaNodal),"\delta_{Mohr}="+num(a.deltaMohr), ...
                 "|\delta_{nodal}-\delta_{Mohr}|="+num(abs(a.deltaNodal-a.deltaMohr))]);
        end
    end
    function campos(a,espacial)
        for k=indices(numel(a.campos))
            b=a.campos{k};
            if espacial
                pagina(sprintf('Barra %d: esfuerzos axiales y cortantes',k),sprintf('s local en m, de 0 a %.6g. Las componentes se refieren a los ejes locales que muestra la geometría.',b.L), ...
                    ["N(s)="+pol(b.N)+"\quad[\mathrm N]", ...
                     "Q_y(s)="+pol(b.Vy)+"\quad[\mathrm N]", ...
                     "Q_z(s)="+pol(b.Vz)+"\quad[\mathrm N]"]);
                pagina(sprintf('Barra %d: torsión y flexión',k),'Momentos físicos sobre la cara positiva de corte. Se mantiene la convención vectorial del modelo espacial.', ...
                    ["T(s)="+pol(b.T)+"\quad[\mathrm{N\,m}]", ...
                     "M_y(s)="+pol(b.My)+"\quad[\mathrm{N\,m}]", ...
                     "M_z(s)="+pol(b.Mz)+"\quad[\mathrm{N\,m}]"]);
            else
                pagina(sprintf('Tramo o barra %d: esfuerzos y desplazamientos',k),sprintf('s local en m, de 0 a %.6g. El desplazamiento transversal se mide en el eje local de la barra.',b.L), ...
                    ["N(s)="+pol(b.N)+"\quad[\mathrm N]", ...
                     "V(s)="+pol(b.V)+"\quad[\mathrm N]", ...
                     "M(s)="+pol(b.M)+"\quad[\mathrm{N\,m}]", ...
                     "v(s)="+pol(b.v)+"\quad[\mathrm m]"]);
            end
        end
    end
end

