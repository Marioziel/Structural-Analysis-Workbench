         "N_i=E_iF_i(\varepsilon_i-\varepsilon_i^0)", ...
         "\mathbf K\mathbf u=\mathbf f+\mathbf R"]);
    matriz(r);
    for j=indices(numel(r.N))
        Ej=valor(d.E,j);Fj=valor(d.F,j);eps0=valor(d.deformacionLibre,j);
