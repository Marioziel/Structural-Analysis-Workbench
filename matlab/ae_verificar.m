function ae_verificar
carpeta=fileparts(mfilename('fullpath'));
for n=1:16
    archivos=dir(fullfile(carpeta,sprintf('Cap%02d_*.mlx',n)));
    assert(numel(archivos)==1,'AE:Biblioteca', ...
        'Debe conservarse un Live Script del capitulo %02d en esta carpeta.',n);
    assert(exist(fullfile(carpeta,sprintf('ae_modelo_%02d.m',n)),'file')==2, ...
        'AE:Biblioteca','Falta el adaptador del capitulo %02d.',n);
end
requeridas={'rm_axial','rm_cercha','rm_seccion','rm_pared','rm_marco', ...
    'rm_marco3d','rm_mohr_plano','rm_mohr3d','rm_resistencia_marco3d', ...
    'rm_dimensionar_marco3d','rm_columna3d','rm_tirantes_rigidos','rm_tensor', ...
    'rm_viga','rm_lineal','rm_equilibrio3d','rm_circular_combinada', ...
    'rm_curva','rm_figura','rm_mohr','rm_esquema_viga','rm_graficar_marco3d','rm_columna'};
for j=1:numel(requeridas)
    assert(exist(fullfile(carpeta,[requeridas{j} '.m']),'file')==2, ...
        'AE:Biblioteca','Falta %s.m. Conserva completa la carpeta.',requeridas{j});
end
for nombre={'ae_seccion_general','ae_union','ae_placa_local','ae_solido3d','ae_equilibrio_solido','ae_casos','ae_factor_mecanico','ae_carga_masa','ae_memoria_ampliacion'}
    assert(exist(fullfile(carpeta,[nombre{1} '.m']),'file')==2,'AE:Biblioteca','Falta %s.m.',nombre{1});
end
end
