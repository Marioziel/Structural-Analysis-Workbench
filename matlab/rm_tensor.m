function r=rm_tensor(S,E,nu)
% Tensor de tensiones simetrico y elasticidad isotropa.
assert(isequal(size(S),[3 3]) && isreal(S) && all(isfinite(S(:))) ...
    && norm(S-S','fro')<=1e-10*max(norm(S,'fro'),realmin), ...
    'RM:Tensor','La matriz debe ser real, finita y simetrica de 3 por 3.');
assert(isscalar(E) && E>0 && isfinite(E) && isscalar(nu) && nu>-1 && nu<.5, ...
    'RM:Material','E positivo y -1 < nu < 0.5.');
[V,D]=eig((S+S')/2); [p,ix]=sort(diag(D),'descend'); V=V(:,ix);
dev=S-trace(S)*eye(3)/3;
r=struct('S',S,'principales',p,'direcciones',V, ...
    'epsilon',(1+nu)*S/E-nu*trace(S)*eye(3)/E, ...
    'VM',sqrt(1.5*sum(dev(:).^2)),'Tresca',p(1)-p(3), ...
    'tauMax',(p(1)-p(3))/2,'I1',trace(S), ...
    'I2',.5*(trace(S)^2-trace(S*S)),'I3',det(S));
end
