function memoria=ae_memoria_ampliacion(s,op)
d=s.entrada;r=s.resultado;paginas=struct('titulo',{},'explicacion',{},'ecuaciones',{});
switch s.analisis
case "seccion_general"
    g=r.geometria;
    pagina('Seccion general: geometria y masa','Los contornos representan la seccion local. En pared delgada se integra sobre la linea media y se omiten terminos de espesor al cubo. La masa supone geometria prismatica y material uniforme.', ...
        ["F=\int_D dA="+num(g.F)+"\ \mathrm{m^2}", ...
         "(y_c,z_c)=("+num(g.centro(1))+","+num(g.centro(2))+")\ \mathrm m", ...
         "I_y="+num(g.Iy)+",\quad I_z="+num(g.Iz)+",\quad I_{yz}="+num(g.Iyz)+"\quad[\mathrm{m^4}]", ...
         "m=\rho FL="+num(r.masa)+"\ \mathrm{kg}"]);
    pagina('Flexion biaxial y esfuerzo axial','Los momentos son vectores locales segun la regla de la mano derecha. Las coordenadas y y z se miden desde el centroide. Los coeficientes incluyen el producto de inercia.', ...
        ["\begin{bmatrix}I_z&I_{yz}\\I_{yz}&I_y\end{bmatrix}\begin{bmatrix}a_y\\a_z\end{bmatrix}=\begin{bmatrix}-M_z\\M_y\end{bmatrix}", ...
         "\sigma_x=\frac{N}{F}+a_y y+a_z z", ...
         "\sigma_x="+num(d.N/g.F)+"+("+num(r.coef(1))+")y+("+num(r.coef(2))+")z\quad[\mathrm{Pa}]", ...
         "\sigma_{min}="+num(r.sigmaMin/1e6)+"\ \mathrm{MPa},\quad\sigma_{max}="+num(r.sigmaMax/1e6)+"\ \mathrm{MPa}"]);
    if d.torsion=="celda_unica"
        pagina('Torsion de una unica celda delgada cerrada','Am es el area encerrada por la linea media. Las paredes comparten el mismo flujo de torsion; el cortante cambia con el espesor. No se calcula el flujo por fuerza transversal ni el centro de cortante.', ...
            ["A_m="+num(r.areaMedia)+"\ \mathrm{m^2}", ...
             "q_T=\frac{T}{2A_m}="+num(r.flujoTorsion)+"\ \mathrm{N/m}", ...
             "\tau_i=\frac{q_T}{t_i},\quad\max|\tau|="+num(max(abs(r.tau))/1e6)+"\ \mathrm{MPa}", ...
             "J=\frac{4A_m^2}{\sum_i L_i/t_i}="+num(r.J)+"\ \mathrm{m^4}", ...
             "\varphi=\frac{TL}{GJ}="+num(r.giro)+"\ \mathrm{rad}"]);
    end
    expresion="\sqrt{\sigma_x^2+3\tau^2}";if d.teoria==3,expresion="\sqrt{\sigma_x^2+4\tau^2}";end
    pagina('Comprobacion de la seccion',"Estado: "+r.estado+". Los limites normales, de cortante y equivalente se introducen por separado. Un resultado parcial conserva mecanismos de la carga sin evaluar.", ...
        ["\sigma_{eq}="+expresion+"\quad\Rightarrow\quad\max\sigma_{eq}="+num(max(r.equivalente)/1e6)+"\ \mathrm{MPa}", ...
         "n=\min(n_{traccion},n_{compresion},n_{cortante},n_{eq})="+num(r.factor), ...
         "MS=\frac{n}{n_{requerido}}-1="+num(r.factor/d.nRequerido-1)]);
case "uniones"
    if d.tipo=="pasador"
        pagina('Perno o pasador: traccion y corte','Las cargas corresponden a un solo elemento. El area de traccion puede diferir del area de corte si hay rosca. El admisible equivalente es un dato explicito y no se deduce de una etiqueta ambigua.', ...
            ["A_c=\frac{\pi d^2}{4}="+num(r.areaCorte)+"\ \mathrm{m^2}", ...
             "\sigma_b=\frac{P_t}{A_t}="+num(r.sigmaPerno/1e6)+"\ \mathrm{MPa}", ...
             "\tau_b=\frac{|P_v|}{i A_c}="+num(r.tauPerno/1e6)+"\ \mathrm{MPa}", ...
             "\sigma_{eq,III}=\sqrt{\sigma_b^2+4\tau_b^2}="+num(r.equivalentePerno/1e6)+"\ \mathrm{MPa}", ...
             "d_{min,corte}=\sqrt{\frac{4|P_v|n_{requerido}}{i\pi[\tau]}}="+num(r.diametroMinCorte)+"\ \mathrm m"]);
        ix=1:size(d.laminas,1);if ~isempty(op.elementos),ix=op.elementos;end
        assert(all(ix==fix(ix)&ix>=1&ix<=size(d.laminas,1)),'AE:Memoria','Indice de lamina fuera de rango.');
        for k=ix(:).'
            pagina(sprintf('Lamina %d: modos nominales de fallo',k),'P es la fuerza transmitida por esta lamina. e se mide del centro del agujero al borde. La seccion neta usa el diametro del agujero; el aplastamiento nominal usa el diametro del perno.', ...
                ["P="+num(d.laminas(k,4))+"\ \mathrm N", ...
                 "\sigma_{neta}=\frac{P}{t(b-d_h)}="+num(r.sigmaNeta(k)/1e6)+"\ \mathrm{MPa}", ...
                 "\sigma_{apl}=\frac{P}{td}="+num(r.sigmaAplastamiento(k)/1e6)+"\ \mathrm{MPa}", ...
                 "\tau_{borde}=\frac{P}{2t(e-d_h/2)}="+num(r.tauDesgarro(k)/1e6)+"\ \mathrm{MPa}"]);
        end
    elseif d.tipo=="soldadura_tope"
        pagina('Soldadura a tope: seccion nominal','Se supone penetracion completa y seccion rectangular de ancho l y espesor t. El eje de flexion es paralelo al ancho. El limite normal debe corresponder al material y procedimiento de la union.', ...
            ["A=lt="+num(r.area)+"\ \mathrm{m^2},\quad W=\frac{lt^2}{6}="+num(r.moduloResistente)+"\ \mathrm{m^3}", ...
             "\sigma_{\pm}=\frac{P}{A}\pm\frac{M}{W}", ...
             "\max|\sigma|="+num(r.demanda/1e6)+"\ \mathrm{MPa}"]);
    elseif d.tipo=="soldadura_filete"
        pagina('Soldadura de filetes bajo cortante directo','Se introduce la garganta efectiva a de cada cordon, no su cateto. Para el modelo uniforme, la fuerza debe pasar por el centro del grupo de gargantas y no aplicar un momento.', ...
            ["A_{ef}=\sum_j a_jL_j="+num(r.area)+"\ \mathrm{m^2}", ...
             "\tau=\frac{|P|}{A_{ef}}="+num(r.tau/1e6)+"\ \mathrm{MPa}"]);
    else
        pagina('Union adhesiva: cortante nominal medio','La formula no representa picos en los extremos, pelado ni dano del adhesivo. Para transferencia longitudinal sobre base rigida existe tambien el modo adhesivo de compatibilidad.', ...
            ["A=bL="+num(r.area)+"\ \mathrm{m^2}", ...
             "\tau_{media}=\frac{|P|}{bL}="+num(r.tau/1e6)+"\ \mathrm{MPa}"]);
    end
    pagina('Margen de las comprobaciones de la union',"Estado: "+r.estado+" para los modos y demandas del modelo indicado. Las tablas identifican el modo que gobierna.", ...
        ["n_j=\frac{[\sigma]_j}{\sigma_j}\ \mathrm{o}\ \frac{[\tau]_j}{\tau_j}", ...
         "n=\min_j n_j="+num(r.factor),"MS=\frac{n}{n_{requerido}}-1="+num(r.factor/d.nRequerido-1)]);
case "placa_local"
    pagina('Placa delgada: compresion y cortante','El coeficiente de compresion pertenece a esta expresion, que ya incorpora su normalizacion. Las condiciones reales de borde deben corresponder al coeficiente elegido.', ...
        ["\sigma_{cr}=k_cE\left(\frac{t}{b}\right)^2="+num(r.sigmaCritica/1e6)+"\ \mathrm{MPa}", ...
         "k_s=5.6+\frac{3.8}{(a/b)^2}="+num(r.kCortante), ...
         "\tau_{cr}=0.9k_sE\left(\frac{t}{b}\right)^2="+num(r.tauCriticaElastica/1e6)+"\ \mathrm{MPa}"]);
    if d.corregirCortante
        pagina('Correccion empirica del cortante critico','La resistencia ultima a cortante es un dato material independiente. Esta correccion no es un calculo no lineal de la placa.', ...
            ["\psi=\frac{\tau_u}{\tau_{cr}}="+num(d.tauUltima/r.tauCriticaElastica), ...
             "\tau_{cr,corr}=\tau_u\frac{1+\psi}{1+\psi+\psi^2}="+num(r.tauCriticaUsada/1e6)+"\ \mathrm{MPa}"]);
    end
    pagina('Alcance de la comprobacion local',"Estado: "+r.estado+". Se limita cada mecanismo por el admisible del material. La actuacion simultanea de compresion y cortante queda pendiente de una ley de interaccion; tampoco se resuelve pandeo inelastico.", ...
        ["\sigma_{lim}=\min(\sigma_{cr},[\sigma]_c)","\tau_{lim}=\min(\tau_{cr,usada},[\tau])", ...
         "n_{min}="+num(r.factor)+",\quad MS=\frac{n_{min}}{n_{requerido}}-1="+num(r.factor/d.nRequerido-1)]);
case "solido3d"
    pagina('Solido 3D: ecuaciones de elasticidad lineal','El modelo representa un unico material isotropo y pequenas deformaciones. Las tracciones se prescriben por unidad de superficie, los apoyos por caras y las fuerzas de volumen mediante densidad y aceleracion efectiva.', ...
        ["\nabla\cdot\boldsymbol\sigma+\rho\mathbf a_{ef}=\mathbf0", ...
         "\boldsymbol\varepsilon=\frac{1}{2}(\nabla\mathbf u+\nabla\mathbf u^T)", ...
         "\boldsymbol\sigma=2\mu\boldsymbol\varepsilon+\lambda\,\mathrm{tr}(\boldsymbol\varepsilon)\mathbf I", ...
         "\mu=\frac{E}{2(1+\nu)},\quad\lambda=\frac{E\nu}{(1+\nu)(1-2\nu)}"]);
    if r.modo=="resolver"
        eqResistencia="n_{VM}=\frac{\sigma_y}{\max\sigma_{VM}}="+num(r.factor);
        if isfield(r,'resistenciaEvaluada')&&~r.resistenciaEvaluada
            eqResistencia="n_{VM}:\quad\mathrm{pendiente}";
        end
        pagina('Discretizacion y resultados del solido','Se emplean tetraedros cuadraticos. La tension equivalente maxima es un indicador nodal; un pico junto a un apoyo o una arista puede ser singular y necesita interpretacion y estudio de malla.', ...
            ["\mathbf K\mathbf u=\mathbf f+\mathbf R", ...
             "N_{nodos}="+num(size(r.modelo.Mesh.Nodes,2))+",\quad N_{tetraedros}="+num(size(r.modelo.Mesh.Elements,2)), ...
             "\max\|\mathbf u\|="+num(r.maxDesplazamiento)+"\ \mathrm m", ...
             "\max\sigma_{VM}="+num(r.maxVM/1e6)+"\ \mathrm{MPa}", ...
             eqResistencia]);
        explicacion="Estado: "+r.estado+". La diferencia entre mallas es un indicador de sensibilidad numerica y no una cota garantizada del error. La tabla conserva todas las mallas calculadas.";
        eq=["e_u=\frac{|u_{h}-u_{prev}|}{|u_h|}="+num(r.errorRelativoU), ...
            "e_\sigma=\frac{|\sigma_{h}-\sigma_{prev}|}{|\sigma_h|}="+num(r.errorRelativoSigma)];
        if height(r.tablaMalla)<2
            explicacion=explicacion+" Solo se ha calculado una malla; los indicadores comparativos quedan pendientes.";
            eq="N_{mallas}=1";
        end
        pagina('Convergencia de indicadores',explicacion,[eq "\mathrm{tolerancia}="+num(d.toleranciaMalla)]);
    end
end
memoria=struct('analisis',s.analisis,'fecha',s.fecha,'entrada',d,'paginas',paginas, ...
    'nota',"Memoria generada desde los datos de esta ejecucion. Consulta el alcance del modelo y los mecanismos pendientes.");
    function pagina(titulo,explicacion,eq)
        if isfield(s,'caso'),titulo=string(s.caso)+" | "+string(titulo);end
        eq=string(eq);paginas(end+1)=struct('titulo',string(titulo),'explicacion',string(explicacion),'ecuaciones',eq);
        ae_pagina(titulo,explicacion,eq);
    end
end
function t=num(v),t=string(ae_numero(v));end
